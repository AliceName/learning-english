"""Filter and sample C4_200M synthetic GEC pairs into train.py's JSONL format.

Streams the source (the Hugging Face ``data.zip``, a directory of ``*.tsv*`` shards,
or a single TSV) without extracting it. Each accepted pair is a sentence-level
``input<TAB>output`` row. The learner-domain dev/test files are copied next to the
new train file so train.py can select checkpoints on W&I dev and audit leakage.

Nothing here downloads data, trains, or calls an external service. Outputs stay
local; the copied W&I files remain under the Cambridge corpus terms.
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
import random
import re
import shutil
from collections import Counter
from difflib import SequenceMatcher
from pathlib import Path
from zipfile import ZipFile

from data import ROOT, normalized_text, read_jsonl
from gec_safety import correction_rejection_reason

POLICY_VERSION = "c4-200m-filtered-v2"
LICENSE_NOTE = ("C4_200M corruption edits: CC BY 4.0 (Stahlberg & Kumar, BEA 2021). "
                "C4 text: ODC-BY; Common Crawl terms of use apply. "
                "Copied W&I dev/test files remain under the Cambridge W&I 2024 terms.")
# Per-corpus provenance written into every row and the report; the filters are shared.
CORPORA = {
    "c4_200m": {"policy": POLICY_VERSION, "prefix": "c4", "user_id": "c4-synthetic", "license": LICENSE_NOTE,
                "warning": "Synthetic corruptions are not learner errors; evaluate on learner-domain and external gold sets."},
    "clang8": {"policy": "clang8-filtered-v1", "prefix": "clang8", "user_id": "clang8-learner",
               "license": ("cLang-8 targets: CC BY-NC-SA 4.0, research/education only (Rothe et al., ACL 2021). "
                           "Lang-8 sources: NAIST terms - research only, no redistribution; cite Mizumoto et al. "
                           "(IJCNLP 2011). Copied W&I dev/test files remain under the Cambridge W&I 2024 terms."),
               "warning": "cLang-8 targets were generated by gT5, not human annotators; evaluate on gold sets."},
}
_TOKENS = re.compile(r"\w+(?:['’]\w+)*|[^\w\s]", re.UNICODE)


def _tokens(text: str) -> list[str]:
    return _TOKENS.findall(text)


def _digest(text: str) -> bytes:
    return hashlib.blake2b(normalized_text(text).encode("utf-8"), digest_size=8).digest()


def edit_profile(source: str, target: str) -> tuple[int, float]:
    """Number of token-level edit regions and the share of tokens they touch."""
    left, right = _tokens(source), _tokens(target)
    edits = changed_left = changed_right = 0
    for op, i1, i2, j1, j2 in SequenceMatcher(None, left, right, autojunk=False).get_opcodes():
        if op != "equal":
            edits += 1
            changed_left += i2 - i1
            changed_right += j2 - j1
    ratio = max(changed_left / max(len(left), 1), changed_right / max(len(right), 1))
    return edits, ratio


# Closed-class words whose substitution, insertion or deletion is a typical grammar
# repair (articles, prepositions, auxiliaries, conjunctions). Pronouns are excluded
# on purpose: "you" -> "we" changes who did something.
FUNCTION_WORDS = frozenset("""
a an the this that these those some any each every no all both either neither much many more most
few little less least several such own other another
of in on at to for from by with within without into onto upon over under about above below across
after before behind beside besides between beyond during except inside outside near off out through
throughout toward towards until up down via per than as like since among amid around along against
and or but nor so yet if because although though while whereas unless whether when where why how
which who whom whose what
is are was were be been being am 's 're 'm
have has had having 've 'd
do does did doing done
will would shall should can could may might must ought 'll
not n't
there here then too also very just only even still already
""".split())
_PUNCTUATION = re.compile(r"[^\w\s]+", re.UNICODE)


def _is_function(token: str) -> bool:
    return token.casefold().replace("’", "'") in FUNCTION_WORDS or bool(_PUNCTUATION.fullmatch(token))


def content_change_reason(source: str, target: str, min_similarity: float) -> str | None:
    """Reject pairs whose 'correction' swaps, adds or drops content words.

    Spelling and inflection repairs stay allowed because the old and new strings
    are close (``picture`` -> ``picturesque``, ``conpletion`` -> ``completion``);
    function-word and punctuation edits stay allowed. A dissimilar content-word
    swap (``required`` -> ``proposed``) is the over-rewriting we want the model not
    to learn.
    """
    if min_similarity <= 0:
        return None
    left, right = _tokens(source), _tokens(target)
    for op, i1, i2, j1, j2 in SequenceMatcher(None, left, right, autojunk=False).get_opcodes():
        old, new = left[i1:i2], right[j1:j2]
        if op == "equal":
            continue
        old_content = [t for t in old if not _is_function(t)]
        new_content = [t for t in new if not _is_function(t)]
        if not old_content and not new_content:
            continue
        if op == "insert":
            return "content_insertion"
        if op == "delete":
            return "content_deletion"
        if not old_content or not new_content:
            return "content_insertion" if new_content else "content_deletion"
        if len(old_content) != len(new_content):
            return "content_substitution"
        for a, b in zip(old_content, new_content):
            if SequenceMatcher(None, a.casefold(), b.casefold(), autojunk=False).ratio() < min_similarity:
                return "content_substitution"
    return None


def iter_pairs(source: Path, per_member: int = 0):
    """Yield (line_number, input, output) or (line_number, None, None) for malformed rows.

    ``per_member`` > 0 reads only that many lines from each shard, spreading the
    sample over all shards instead of the start of the first one.
    """
    def rows(stream):
        for count, raw in enumerate(stream):
            if per_member and count >= per_member:
                break
            yield raw.replace("\0", " ").rstrip("\r\n")

    def shard_lines():
        if source.is_dir():
            for path in sorted(p for p in source.iterdir() if ".tsv" in p.name and p.is_file()):
                with path.open(encoding="utf-8", errors="replace", newline="") as stream:
                    yield from rows(stream)
        elif source.suffix.lower() == ".zip":
            with ZipFile(source) as archive:
                members = sorted(name for name in archive.namelist()
                                 if ".tsv" in Path(name).name and not name.endswith("/"))
                if not members:
                    raise ValueError("No *.tsv* members found in the ZIP")
                for name in members:
                    with archive.open(name) as raw:
                        with io.TextIOWrapper(raw, encoding="utf-8", errors="replace", newline="") as stream:
                            yield from rows(stream)
        else:
            with source.open(encoding="utf-8", errors="replace", newline="") as stream:
                yield from rows(stream)

    for number, line in enumerate(shard_lines(), start=1):
        fields = line.split("\t")
        if len(fields) != 2:
            yield number, None, None
        else:
            yield number, fields[0].strip(), fields[1].strip()


def rejection(source: str, target: str, args) -> str | None:
    if not source or not target:
        return "empty"
    if source == target:
        return "identical_pair"
    for text in (source, target):
        if len(text.encode("utf-8")) > args.max_bytes:
            return "too_many_bytes"
        words = len(text.split())
        if words < args.min_words or words > args.max_words:
            return "word_count"
    if "\t" in target or "\n" in source or "\n" in target:
        return "layout"
    if "�" in source or "�" in target:
        return "encoding_damage"
    edits, ratio = edit_profile(source, target)
    if edits > args.max_edits:
        return "too_many_edits"
    if ratio > args.max_change_ratio:
        return "change_ratio"
    guard = correction_rejection_reason(source, target)
    if guard:
        return f"guard:{guard}"
    return content_change_reason(source, target, args.min_content_similarity)


def prepare(args) -> dict:
    source, output, wi_dir = Path(args.source), Path(args.output), Path(args.wi_dir)
    corpus = CORPORA[args.corpus]
    if output.exists() and any(output.iterdir()):
        raise ValueError("Output is not empty; use a new directory")
    if not 0 <= args.identity_ratio < 1 or args.sample < 1:
        raise ValueError("Sample must be positive and identity ratio in [0, 1)")
    held = {split: wi_dir / f"gec-{split}.jsonl" for split in ("dev", "test")}
    if not held["dev"].is_file():
        raise ValueError("W&I gec-dev.jsonl is required for checkpoint selection")
    blocked = set()
    for path in held.values():
        if path.is_file():
            for row in read_jsonl(path):
                for field in ("text", "corrected_text"):
                    if isinstance(row.get(field), str) and row[field].strip():
                        blocked.add(_digest(row[field]))

    rng = random.Random(args.seed)
    reasons, seen = Counter(), set()
    reservoir, accepted, read = [], 0, 0
    for number, text, corrected in iter_pairs(source, args.max_read_per_member):
        if args.max_read and read >= args.max_read:
            break
        read += 1
        if text is None:
            reasons["malformed"] += 1
            continue
        reason = rejection(text, corrected, args)
        if reason is None:
            key = _digest(text)
            if key in seen:
                reason = "duplicate_input"
            elif key in blocked or _digest(corrected) in blocked:
                reason = "wi_heldout_overlap"
            else:
                seen.add(key)
        if reason:
            reasons[reason] += 1
            continue
        accepted += 1
        item = (number, text, corrected)
        if len(reservoir) < args.sample:
            reservoir.append(item)
        else:
            slot = rng.randrange(accepted)
            if slot < args.sample:
                reservoir[slot] = item
    if not reservoir:
        raise ValueError("No pair passed the filters")

    rng.shuffle(reservoir)
    identity_count = round(len(reservoir) * args.identity_ratio)
    rows, inputs = [], set()
    for index, (number, text, corrected) in enumerate(reservoir):
        kind = "identity" if index < identity_count else "error"
        source_text = corrected if kind == "identity" else text
        key = _digest(source_text)
        if key in inputs:
            reasons["duplicate_after_identity"] += 1
            continue
        inputs.add(key)
        rows.append({"id": f"{corpus['prefix']}:{number}:{kind}", "user_id": corpus["user_id"], "text": source_text,
                     "corrected_text": corrected, "source": args.corpus, "pair_kind": kind,
                     "source_line": number})

    output.mkdir(parents=True, exist_ok=True)
    with (output / "gec-train.jsonl").open("w", encoding="utf-8", newline="\n") as stream:
        for row in rows:
            stream.write(json.dumps(row, ensure_ascii=False) + "\n")
    for split, path in held.items():
        if path.is_file():
            shutil.copyfile(path, output / f"gec-{split}.jsonl")
    preview = rng.sample(rows, min(args.preview, len(rows)))
    with (output / "preview.private.jsonl").open("w", encoding="utf-8", newline="\n") as stream:
        for row in preview:
            stream.write(json.dumps(row, ensure_ascii=False) + "\n")

    def sha(path: Path) -> str:
        with path.open("rb") as stream:
            return hashlib.file_digest(stream, "sha256").hexdigest()

    kinds = Counter(row["pair_kind"] for row in rows)
    report = {
        "encoding_policy": corpus["policy"],
        "corpus": args.corpus,
        "source_name": source.name,
        "source_kind": "directory" if source.is_dir() else source.suffix.lower().lstrip(".") or "file",
        "source_sha256": sha(source) if source.is_file() and args.hash_source else None,
        "parameters": {name: getattr(args, name) for name in (
            "sample", "identity_ratio", "seed", "max_read", "max_read_per_member", "max_bytes", "min_words", "max_words",
            "max_edits", "max_change_ratio", "min_content_similarity")},
        "rows_read": read, "pairs_accepted_before_sampling": accepted,
        "rejections": dict(sorted(reasons.items())),
        "train_rows": len(rows), "train_pair_kinds": dict(kinds),
        "wi_heldout_reference": {split: path.name for split, path in held.items() if path.is_file()},
        "license": corpus["license"],
        "warnings": [
            corpus["warning"],
            "Automatic filters replace manual review; meaning changes can still pass.",
            "Keep copied W&I files and any adapter fine-tuned on them private under Cambridge terms.",
        ],
        "prepared_files_sha256": {path.name: sha(path) for path in sorted(output.glob("gec-*.jsonl"))},
    }
    (output / "preparation-report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    return report


def parser() -> argparse.ArgumentParser:
    result = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    result.add_argument("--source", type=Path, required=True,
                        help="C4_200M data.zip, a directory of *.tsv* shards, or one TSV file")
    result.add_argument("--output", type=Path, required=True, help="New, empty output directory")
    result.add_argument("--corpus", choices=sorted(CORPORA), default="c4_200m",
                        help="Provenance labels and license note for the source TSV (filters are identical)")
    result.add_argument("--wi-dir", type=Path, default=ROOT / "data" / "prepared-first-final",
                        help="Prepared W&I directory providing gec-dev.jsonl (and gec-test.jsonl)")
    result.add_argument("--sample", type=int, default=500_000, help="Train rows to keep")
    result.add_argument("--identity-ratio", type=float, default=0.28,
                        help="Share of sampled rows turned into unchanged (target -> target) pairs")
    result.add_argument("--seed", type=int, default=2026)
    result.add_argument("--max-read", type=int, default=0, help="Stop after this many rows (0 = all)")
    result.add_argument("--max-read-per-member", type=int, default=0,
                        help="Read at most this many lines from each shard (0 = all)")
    result.add_argument("--max-bytes", type=int, default=380)
    result.add_argument("--min-words", type=int, default=3)
    result.add_argument("--max-words", type=int, default=60)
    result.add_argument("--max-edits", type=int, default=6)
    result.add_argument("--max-change-ratio", type=float, default=0.4)
    result.add_argument("--min-content-similarity", type=float, default=0.6,
                        help="Min character similarity for a content-word substitution (0 disables the check)")
    result.add_argument("--preview", type=int, default=50)
    result.add_argument("--no-hash-source", dest="hash_source", action="store_false",
                        help="Skip hashing a large source file")
    return result


def main(argv=None):
    report = prepare(parser().parse_args(argv))
    print(json.dumps({key: report[key] for key in (
        "rows_read", "pairs_accepted_before_sampling", "train_rows", "train_pair_kinds", "rejections")},
        indent=2))


if __name__ == "__main__":
    main()
